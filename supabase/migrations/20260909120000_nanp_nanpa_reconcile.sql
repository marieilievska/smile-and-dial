-- Reconcile nanp_area_codes against the NANPA NPA Database itself.
--
-- The 2026-09-08 pass (20260908140000) added nine overlay codes from a list of
-- area codes seen on live leads. That list was hand-collected, and two entries
-- on it were simply wrong about which state the code belongs to:
--
--   728 -- filed under LA (as an overlay of 985). It is FLORIDA: the overlay of
--          561, serving Palm Beach County, in service 2023-03-10.
--   645 -- filed under MD (as an overlay of 301). It is FLORIDA: the third code
--          in the 305/786 complex, serving Miami-Dade and the Keys, in service
--          2023-08-04.
--
-- A wrong state is worse than a missing one. A missing code leaves
-- regionForAreaCode() null, so number-pool scores matchTier "none" and the lead
-- is dialled with no local presence -- visibly nothing. A wrong state MATCHES:
-- dial_queue and pickPoolNumber happily hand a Louisiana number to a Florida
-- lead and stamp the call local_match = 'state', so the local-presence metric
-- reports success while the lead sees an out-of-state caller ID.
--
-- So this pass stopped trusting observation and went to the source: the NANPA
-- NPA Database (reports.nanpa.com/public/npa_report.csv, file dated
-- 09/09/2026), filtered to codes that are geographic (USE = 'G') and actually
-- in service (IN_SERVICE = 'Y'). Every in-service geographic NPA in the 50
-- states + DC is now present -- 372 of them, up from 341 -- plus 56 Canadian
-- rows. Beyond the two corrections above, 31 US codes were missing outright,
-- all overlays placed in service between 2019 and 2026:
--
--   483 AL  659 AL  327 AR  350 CA  357 CA  369 CA  738 CA  837 CA  748 CO
--   324 FL  861 IL  457 LA  924 MN  235 MO  471 MS  472 NC  465 NY  624 NY
--   283 OH  326 OH  436 OH  582 PA  835 PA  821 SC  729 TN  621 TX  686 VA
--   826 VA  948 VA  274 WI  353 WI
--
-- Canada gained 257 (the Vancouver 604 overlay) and 942 (the Toronto 416
-- overlay). 922 was checked and deliberately NOT added: NANPA lists it as an
-- Easily Recognizable Code, non-geographic and not in service, so it has no
-- state to map to. Puerto Rico (787/939) and the other US territories stay out
-- as before -- the map's scope is the 50 states + DC.
--
-- Additive and idempotent: a full re-seed via upsert, so this file remains the
-- whole truth rather than a patch that has to be read alongside two others. No
-- row is deleted, so re-running it is safe.
--
-- Regenerate with: npx tsx scripts/gen-nanp-seed.mjs

